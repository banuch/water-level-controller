#!/usr/bin/env bash
# Generates the OTA release signing key pair (ECDSA P-256).
# Run on an OFFLINE machine. Store ota_signing_key.pem in a hardware token or
# offline vault; NEVER commit it. Only the generated public header is built in.
#
#   tools/ota_keygen.sh <output-dir>
set -euo pipefail
OUT=${1:?usage: ota_keygen.sh <output-dir>}
mkdir -p "$OUT"
umask 077
openssl ecparam -name prime256v1 -genkey -noout -out "$OUT/ota_signing_key.pem"
openssl ec -in "$OUT/ota_signing_key.pem" -pubout -out "$OUT/ota_pubkey.pem" 2>/dev/null
{
  echo "// Generated by tools/ota_keygen.sh — public key only."
  echo "#pragma once"
  printf '#define WINTEK_OTA_PUBKEY_PEM \\\n'
  sed 's/.*/  "&\\n" \\/' "$OUT/ota_pubkey.pem"
  echo '  ""'
} > "$OUT/ota_pubkey.pem.h"
echo "private key : $OUT/ota_signing_key.pem  (keep offline)"
echo "public hdr  : $OUT/ota_pubkey.pem.h"
echo "build with  : copy ota_pubkey.pem.h to firmware/include/ and add"
echo "              -DWINTEK_OTA_PUBKEY_FILE=\\\"ota_pubkey.pem.h\\\" to build_flags"
